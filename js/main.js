const COMMENTS_KEY = 'recipe_comments';
const RATINGS_KEY = 'recipe_ratings';

function getRecipeComments(recipeName) {
    const allComments = JSON.parse(localStorage.getItem(COMMENTS_KEY) || '{}');
    return allComments[recipeName] || [];
}

function addComment(recipeName, commentText) {
    const currentUser = getCurrentUser();
    if (!currentUser) {
        alert('⚠️ Войдите в аккаунт, чтобы оставлять комментарии!');
        return false;
    }
    if (!commentText.trim()) {
        alert('Введите текст комментария');
        return false;
    }
    
    // Сохраняем комментарий к рецепту
    const allComments = JSON.parse(localStorage.getItem(COMMENTS_KEY) || '{}');
    if (!allComments[recipeName]) allComments[recipeName] = [];
    const newComment = {
        username: currentUser.username,
        text: commentText.trim(),
        date: new Date().toLocaleString(),
        likes: 0
    };
    allComments[recipeName].push(newComment);
    localStorage.setItem(COMMENTS_KEY, JSON.stringify(allComments));
    
    // Сохраняем комментарий в профиль пользователя
    const users = getUsers();
    if (users[currentUser.username]) {
        if (!users[currentUser.username].comments) users[currentUser.username].comments = [];
        users[currentUser.username].comments.push({
            recipeName: recipeName,
            text: commentText.trim(),
            date: new Date().toLocaleString()
        });
        saveUsers(users);
    }
    
    return true;
}

function getRecipeRating(recipeName) {
    const allRatings = JSON.parse(localStorage.getItem(RATINGS_KEY) || '{}');
    const ratings = allRatings[recipeName] || [];
    if (ratings.length === 0) return { average: 0, count: 0 };
    const sum = ratings.reduce((a, b) => a + b.rating, 0);
    return { average: (sum / ratings.length).toFixed(1), count: ratings.length };
}

function setRating(recipeName, ratingValue) {
    const currentUser = getCurrentUser();
    if (!currentUser) {
        alert('⚠️ Войдите в аккаунт, чтобы оценивать рецепты!');
        return false;
    }
    if (ratingValue < 1 || ratingValue > 5) return false;
    
    const allRatings = JSON.parse(localStorage.getItem(RATINGS_KEY) || '{}');
    if (!allRatings[recipeName]) allRatings[recipeName] = [];
    const existingIndex = allRatings[recipeName].findIndex(r => r.username === currentUser.username);
    if (existingIndex !== -1) {
        allRatings[recipeName][existingIndex].rating = ratingValue;
    } else {
        allRatings[recipeName].push({ username: currentUser.username, rating: ratingValue });
    }
    localStorage.setItem(RATINGS_KEY, JSON.stringify(allRatings));
    
    // Сохраняем оценку в профиль пользователя
    const users = getUsers();
    if (users[currentUser.username]) {
        if (!users[currentUser.username].ratings) users[currentUser.username].ratings = {};
        users[currentUser.username].ratings[recipeName] = ratingValue;
        saveUsers(users);
    }
    
    return true;
}

function getUserRating(recipeName) {
    const currentUser = getCurrentUser();
    if (!currentUser) return null;
    const allRatings = JSON.parse(localStorage.getItem(RATINGS_KEY) || '{}');
    const ratings = allRatings[recipeName] || [];
    const userRating = ratings.find(r => r.username === currentUser.username);
    return userRating ? userRating.rating : null;
}

