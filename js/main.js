function hideAllPagesOnLoad() {
    const allPagesToHide = document.querySelectorAll('#homePage, #catalogPage, #favoritesPage, #plannerPage, #travelPage, #aboutPage, [id$="ListPage"], [id$="DetailPage"], #countryDetailPage, #profilePage');
    allPagesToHide.forEach(page => {
        if(page) page.classList.add('hidden-page');
    });
    console.log('✅ Все страницы скрыты при загрузке');
}

// Вызываем немедленно
hideAllPagesOnLoad();

// Дублируем через DOMContentLoaded для надежности
document.addEventListener('DOMContentLoaded', function() {
    hideAllPagesOnLoad();
    // Показываем домашнюю страницу
    if(homePage) homePage.classList.remove('hidden-page');
});

function toggleMobile() {
  const isOpen = mobileMenu.style.display === 'flex';
  mobileMenu.style.display = isOpen ? 'none' : 'flex';
  burgerBtn.classList.toggle('active', !isOpen);
}
burgerBtn?.addEventListener('click', (e) => { e.stopPropagation(); toggleMobile(); });
document.addEventListener('click', (e) => { if (window.innerWidth <= 820 && mobileMenu && !e.target.closest('.header') && mobileMenu.style.display === 'flex') { mobileMenu.style.display = 'none'; burgerBtn.classList.remove('active'); } });
window.addEventListener('resize', () => { if (window.innerWidth > 820 && mobileMenu) mobileMenu.style.display = 'none'; if (window.innerWidth > 820 && burgerBtn) burgerBtn.classList.remove('active'); });

