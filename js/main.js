const PLAN_KEY = 'weekly_meal_plan';

const daysOfWeek = ['Понедельник', 'Вторник', 'Среда', 'Четверг', 'Пятница', 'Суббота', 'Воскресенье'];

// Получить план на неделю
function getWeeklyPlan() {
    const plan = localStorage.getItem(PLAN_KEY);
    return plan ? JSON.parse(plan) : {};
}

// Сохранить план
function saveWeeklyPlan(plan) {
    localStorage.setItem(PLAN_KEY, JSON.stringify(plan));
}

// Добавить рецепт в день
function addRecipeToDay(recipeName, dayIndex) {
    let plan = getWeeklyPlan();
    if (!plan[dayIndex]) plan[dayIndex] = [];
    if (!plan[dayIndex].includes(recipeName)) {
        plan[dayIndex].push(recipeName);
        saveWeeklyPlan(plan);
        renderPlannerPage();
        showToast(`✅ "${recipeName}" добавлен в ${daysOfWeek[dayIndex]}`);
    } else {
        showToast(`⚠️ "${recipeName}" уже есть в ${daysOfWeek[dayIndex]}`);
    }
}

// Удалить рецепт из дня
function removeRecipeFromDay(recipeName, dayIndex) {
    let plan = getWeeklyPlan();
    if (plan[dayIndex]) {
        plan[dayIndex] = plan[dayIndex].filter(r => r !== recipeName);
        if (plan[dayIndex].length === 0) delete plan[dayIndex];
        saveWeeklyPlan(plan);
        renderPlannerPage();
        showToast(`❌ "${recipeName}" удалён из ${daysOfWeek[dayIndex]}`);
    }
}

