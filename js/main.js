function addThemeToggleToMenu() {
    // Добавляем в основное меню (nav-links)
    const navMenu = document.querySelector('.nav-links');
    if (navMenu && !navMenu.querySelector('.theme-switch-wrapper')) {
        const themeWrapper = document.createElement('div');
        themeWrapper.className = 'theme-switch-wrapper';
        themeWrapper.style.cssText = 'margin-left: 10px; display: flex; align-items: center;';
        themeWrapper.innerHTML = `
            <label class="theme-switch">
                <input type="checkbox" id="themeToggleInMenu">
                <span class="slider"></span>
            </label>
        `;
        navMenu.appendChild(themeWrapper);
        
        // Добавляем обработчик для нового переключателя
        const newThemeToggle = document.getElementById('themeToggleInMenu');
        if (newThemeToggle) {
            const savedTheme = localStorage.getItem('theme');
            if (savedTheme === 'dark') {
                newThemeToggle.checked = true;
                document.body.classList.add('dark-theme');
            }
            
            newThemeToggle.addEventListener('change', function() {
                if (this.checked) {
                    document.body.classList.add('dark-theme');
                    localStorage.setItem('theme', 'dark');
                    // Синхронизируем с основным переключателем, если есть
                    const mainToggle = document.getElementById('themeToggle');
                    if (mainToggle) mainToggle.checked = true;
                } else {
                    document.body.classList.remove('dark-theme');
                    localStorage.setItem('theme', 'light');
                    const mainToggle = document.getElementById('themeToggle');
                    if (mainToggle) mainToggle.checked = false;
                }
                // Обновляем дашборд если открыт
                updateAdminBlocksColors();
            });
        }
    }
    
    // Добавляем в мобильное меню
    const mobileMenu = document.getElementById('mobileMenu');
    if (mobileMenu && !mobileMenu.querySelector('.theme-switch-wrapper')) {
        const mobileThemeWrapper = document.createElement('div');
        mobileThemeWrapper.className = 'theme-switch-wrapper';
        mobileThemeWrapper.style.cssText = 'padding: 10px 0; display: flex; align-items: center; gap: 10px;';
        mobileThemeWrapper.innerHTML = `
            <span style="color: white;">Тёмная тема</span>
            <label class="theme-switch">
                <input type="checkbox" id="themeToggleMobile">
                <span class="slider"></span>
            </label>
        `;
        mobileMenu.appendChild(mobileThemeWrapper);
        
        const mobileToggle = document.getElementById('themeToggleMobile');
        if (mobileToggle) {
            const savedTheme = localStorage.getItem('theme');
            if (savedTheme === 'dark') {
                mobileToggle.checked = true;
            }
            
            mobileToggle.addEventListener('change', function() {
                if (this.checked) {
                    document.body.classList.add('dark-theme');
                    localStorage.setItem('theme', 'dark');
                    const mainToggle = document.getElementById('themeToggleInMenu');
                    if (mainToggle) mainToggle.checked = true;
                } else {
                    document.body.classList.remove('dark-theme');
                    localStorage.setItem('theme', 'light');
                    const mainToggle = document.getElementById('themeToggleInMenu');
                    if (mainToggle) mainToggle.checked = false;
                }
                updateAdminBlocksColors();
            });
        }
    }
}

