// ЗАМЕНИТЕ существующую функцию showPage на ЭТУ:

function showPage(pageId) {
  // 1. Собираем ВСЕ возможные страницы
  const allPages = [
    homePage, catalogPage, 
    saladsListPage, soupsListPage, mainsListPage, dessertsListPage, 
    drinksListPage, bakeryListPage, breakfastListPage, saucesListPage,
    saladDetailPage, soupDetailPage, mainDetailPage, dessertDetailPage, 
    drinkDetailPage, bakeryDetailPage, breakfastDetailPage, sauceDetailPage,
    travelPage, aboutPage, countryDetailPage, 
    document.getElementById('favoritesPage'), 
    document.getElementById('profilePage'),
    document.getElementById('plannerPage'),
    document.getElementById('itTeamPage'),
    document.getElementById('devCenterPage'),
    document.getElementById('aiAssistantPage')
  ];
  
  // 2. Скрываем ВСЕ страницы
  allPages.forEach(page => { 
    if(page) page.classList.add('hidden-page'); 
  });
  
  // 3. Показываем ТОЛЬКО запрошенную страницу
  if (pageId === 'home' && homePage) homePage.classList.remove('hidden-page');
  else if (pageId === 'catalog' && catalogPage) catalogPage.classList.remove('hidden-page');
  else if (pageId === 'saladsList' && saladsListPage) saladsListPage.classList.remove('hidden-page');
  else if (pageId === 'soupsList' && soupsListPage) soupsListPage.classList.remove('hidden-page');
  else if (pageId === 'mainsList' && mainsListPage) mainsListPage.classList.remove('hidden-page');
  else if (pageId === 'dessertsList' && dessertsListPage) dessertsListPage.classList.remove('hidden-page');
  else if (pageId === 'drinksList' && drinksListPage) drinksListPage.classList.remove('hidden-page');
  else if (pageId === 'bakeryList' && bakeryListPage) bakeryListPage.classList.remove('hidden-page');
  else if (pageId === 'breakfastList' && breakfastListPage) breakfastListPage.classList.remove('hidden-page');
  else if (pageId === 'saucesList' && saucesListPage) saucesListPage.classList.remove('hidden-page');
  else if (pageId === 'saladDetail' && saladDetailPage) saladDetailPage.classList.remove('hidden-page');
  else if (pageId === 'soupDetail' && soupDetailPage) soupDetailPage.classList.remove('hidden-page');
  else if (pageId === 'mainDetail' && mainDetailPage) mainDetailPage.classList.remove('hidden-page');
  else if (pageId === 'dessertDetail' && dessertDetailPage) dessertDetailPage.classList.remove('hidden-page');
  else if (pageId === 'drinkDetail' && drinkDetailPage) drinkDetailPage.classList.remove('hidden-page');
  else if (pageId === 'bakeryDetail' && bakeryDetailPage) bakeryDetailPage.classList.remove('hidden-page');
  else if (pageId === 'breakfastDetail' && breakfastDetailPage) breakfastDetailPage.classList.remove('hidden-page');
  else if (pageId === 'sauceDetail' && sauceDetailPage) sauceDetailPage.classList.remove('hidden-page');
  else if (pageId === 'travel' && travelPage) travelPage.classList.remove('hidden-page');
  else if (pageId === 'about' && aboutPage) aboutPage.classList.remove('hidden-page');
  else if (pageId === 'countryDetail' && countryDetailPage) countryDetailPage.classList.remove('hidden-page');
  else if (pageId === 'favorites') {
    const favPage = document.getElementById('favoritesPage');
    if(favPage) {
      favPage.classList.remove('hidden-page');
      if(typeof renderFavoritesPage === 'function') renderFavoritesPage();
    }
  }
  else if (pageId === 'profile') {
    const profilePageElem = document.getElementById('profilePage');
    if(profilePageElem) {
      profilePageElem.classList.remove('hidden-page');
      if(typeof renderProfilePage === 'function') renderProfilePage();
    }
  }
  else if (pageId === 'planner') {
    const plannerPageElem = document.getElementById('plannerPage');
    if(plannerPageElem) {
      plannerPageElem.classList.remove('hidden-page');
      if(typeof renderPlannerPage === 'function') renderPlannerPage();
    }
  }
  else if (pageId === 'itTeam') {
    const itPage = document.getElementById('itTeamPage');
    if(itPage) itPage.classList.remove('hidden-page');
  }
  else if (pageId === 'devCenter') {
    const devPage = document.getElementById('devCenterPage');
    if(devPage) devPage.classList.remove('hidden-page');
  }
  else if (pageId === 'aiAssistant') {
    const aiPage = document.getElementById('aiAssistantPage');
    if(aiPage) aiPage.classList.remove('hidden-page');
  }
  
  // 4. Обновляем активные классы в навигации
  navLinks.forEach(link => {
    link.classList.remove('active');
    if ((pageId === 'saladsList' || pageId === 'soupsList' || pageId === 'mainsList' || pageId === 'dessertsList' || pageId === 'drinksList' || pageId === 'bakeryList' || pageId === 'breakfastList' || pageId === 'saucesList' || pageId === 'saladDetail' || pageId === 'soupDetail' || pageId === 'mainDetail' || pageId === 'dessertDetail' || pageId === 'drinkDetail' || pageId === 'bakeryDetail' || pageId === 'breakfastDetail' || pageId === 'sauceDetail') && link.getAttribute('data-page') === 'catalog') {
      link.classList.add('active');
    } else if (link.getAttribute('data-page') === pageId) {
      link.classList.add('active');
    } else if (pageId === 'countryDetail' && link.getAttribute('data-page') === 'travel') {
      link.classList.add('active');
    } else if (pageId === 'favorites' && link.getAttribute('data-fav-btn')) {
      link.classList.add('active');
    } else if (pageId === 'planner' && link.getAttribute('data-page') === 'planner') {
      link.classList.add('active');
    }
  });
  
  // 5. Закрываем мобильное меню
  if (window.innerWidth <= 820 && mobileMenu) { 
    mobileMenu.style.display = 'none'; 
    burgerBtn?.classList.remove('active'); 
  }
  
  // 6. Добавляем сердечки после отображения
  setTimeout(() => addHeartsToAllRecipes(), 150);
}

