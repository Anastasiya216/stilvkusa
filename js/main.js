// Функция поиска рецептов по продуктам
function findRecipesByIngredients(ingredients) {
    const userInput = ingredients.toLowerCase().trim();
    const matchedRecipes = new Map();
    
    for (const [product, recipes] of Object.entries(recipeKnowledgeBase)) {
        if (userInput.includes(product) || product.includes(userInput.split(' ')[0])) {
            recipes.forEach(recipe => {
                matchedRecipes.set(recipe, (matchedRecipes.get(recipe) || 0) + 1);
            });
        }
    }
    
    if (matchedRecipes.size === 0) return null;
    
    return Array.from(matchedRecipes.entries())
        .sort((a, b) => b[1] - a[1])
        .slice(0, 8)
        .map(([recipe]) => recipe);
}

// Функция для генерации ответа ИИ
function generateAIResponse(userMessage) {
    const recipes = findRecipesByIngredients(userMessage);
    
    if (!recipes || recipes.length === 0) {
        return {
            response: `🍽️ Из ваших продуктов "${userMessage}" я не смог подобрать рецепты. Попробуйте написать другие продукты (например: курица, рис, помидоры, картошка, яйца).`,
            recipes: []
        };
    }
    
    // Формируем ответ с КАЖДЫМ рецептом в формате "1. **Название рецепта**"
    let response = `🍳 По вашим продуктам я нашёл рецепты:\n\n`;
    
    recipes.forEach((recipe, index) => {
        response += `${index + 1}. **${recipe}**\n`;
    });
    
    response += `\n💡 **Совет:** Нажмите на название рецепта выше, чтобы открыть его!`;
    
    return { response, recipes };
}

// Функция добавления сообщения в чат - КАЖДЫЙ РЕЦЕПТ СТАНОВИТСЯ ССЫЛКОЙ
function addMessageToChat(text, isUser = false, recipesList = null) {
    const chatContainer = document.getElementById('chatMessages');
    if (!chatContainer) return;
    
    const messageDiv = document.createElement('div');
    messageDiv.style.display = 'flex';
    messageDiv.style.marginBottom = '15px';
    messageDiv.style.justifyContent = isUser ? 'flex-end' : 'flex-start';
    
    const bubbleDiv = document.createElement('div');
    bubbleDiv.style.background = isUser ? '#6a1b2a' : '#f0f0f0';
    bubbleDiv.style.color = isUser ? 'white' : '#333';
    bubbleDiv.style.padding = '10px 15px';
    bubbleDiv.style.borderRadius = '20px';
    bubbleDiv.style.borderTopRightRadius = isUser ? '0' : '20px';
    bubbleDiv.style.borderTopLeftRadius = isUser ? '20px' : '0';
    bubbleDiv.style.maxWidth = '80%';
    bubbleDiv.style.whiteSpace = 'pre-wrap';
    bubbleDiv.style.wordBreak = 'break-word';
    
    let htmlContent = text.replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>');
    
    // КЛЮЧЕВОЕ ИСПРАВЛЕНИЕ: Делаем ссылкой КАЖДЫЙ рецепт из списка
    if (recipesList && recipesList.length > 0) {
        recipesList.forEach(recipe => {
            // Экранируем спецсимволы в названии рецепта для RegExp
            const escapedRecipe = recipe.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
            
            // Создаём HTML ссылки
            const recipeLink = `<span class="ai-recipe-link" data-recipe="${recipe.replace(/"/g, '&quot;')}" style="color: ${isUser ? '#fff' : '#6a1b2a'}; text-decoration: underline; cursor: pointer; font-weight: bold; display: inline-block;">📖 ${recipe}</span>`;
            
            // Заменяем название рецепта на ссылку (с учётом формата "1. **Название**")
            htmlContent = htmlContent.replace(new RegExp(`(\\d+\\.\\s*)\\*\\*${escapedRecipe}\\*\\*`, 'g'), `$1${recipeLink}`);
            htmlContent = htmlContent.replace(new RegExp(`\\*\\*${escapedRecipe}\\*\\*`, 'g'), recipeLink);
            htmlContent = htmlContent.replace(new RegExp(escapedRecipe, 'g'), recipeLink);
        });
    }
    
    bubbleDiv.innerHTML = htmlContent;
    messageDiv.appendChild(bubbleDiv);
    chatContainer.appendChild(messageDiv);
    chatContainer.scrollTop = chatContainer.scrollHeight;
    
    // Сохраняем историю
    saveChatHistoryToLocal();
    
    // Добавляем обработчики на ВСЕ ссылки
    setTimeout(() => {
        const allLinks = bubbleDiv.querySelectorAll('.ai-recipe-link');
        console.log(`🔗 Найдено ссылок на рецепты: ${allLinks.length}`);
        
        allLinks.forEach(link => {
            // Удаляем старый обработчик и создаём новый
            const newLink = link.cloneNode(true);
            link.parentNode.replaceChild(newLink, link);
            
            newLink.addEventListener('click', (e) => {
                e.stopPropagation();
                e.preventDefault();
                const recipeName = newLink.getAttribute('data-recipe');
                console.log(`🔗 Клик по рецепту: ${recipeName}`);
                openRecipeByName(recipeName);
            });
        });
    }, 50);
}

