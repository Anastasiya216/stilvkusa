// ==================== УДАЛЕНИЕ КОММЕНТАРИЕВ ====================

function deleteComment(recipeName, commentIndex, commentUsername) {
    const currentUser = getCurrentUser();
    if (!currentUser) {
        alert('⚠️ Войдите в аккаунт!');
        return false;
    }
    
    // Проверяем, что пользователь удаляет свой комментарий
    if (commentUsername !== currentUser.username) {
        alert('❌ Вы можете удалять только свои комментарии!');
        return false;
    }
    
    // Удаляем комментарий из хранилища рецептов
    const allComments = JSON.parse(localStorage.getItem(COMMENTS_KEY) || '{}');
    if (allComments[recipeName] && allComments[recipeName][commentIndex]) {
        allComments[recipeName].splice(commentIndex, 1);
        // Если комментариев больше нет, удаляем ключ рецепта
        if (allComments[recipeName].length === 0) {
            delete allComments[recipeName];
        }
        localStorage.setItem(COMMENTS_KEY, JSON.stringify(allComments));
    }
    
    // Удаляем комментарий из профиля пользователя
    const users = getUsers();
    if (users[currentUser.username] && users[currentUser.username].comments) {
        users[currentUser.username].comments = users[currentUser.username].comments.filter(
            c => !(c.recipeName === recipeName && c.text === allComments[recipeName]?.[commentIndex]?.text)
        );
        saveUsers(users);
    }
    
    return true;
}

