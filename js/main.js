// Открытие рецепта по имени (С СИНОНИМАМИ)
function openRecipeByName(recipeName) {
    console.log(`🔍 Ищем рецепт: "${recipeName}"`);
    
    const aiPage = document.getElementById('aiAssistantPage');
    if (aiPage) aiPage.classList.add('hidden-page');
    
    // ========== СЛОВАРЬ СИНОНИМОВ ==========
    const synonyms = {
        "курица по-французски": "Мясо по-французски с картофелем",
        "курица по французски": "Мясо по-французски с картофелем",
        "курица с картошкой в духовке": "Мясо по-французски с картофелем",
        "чикен карри": "Чикен Карри",
        "chicken curry": "Чикен Карри",
        "карри с курицей": "Чикен Карри",
        "том ям": "Том Ям",
        "том-ям": "Том Ям",
        "пад тай": "Пад Тай",
        "падтай": "Пад Тай"
    };
    
    // Проверяем синонимы
    let targetRecipe = recipeName;
    const lowerName = recipeName.toLowerCase();
    for (let [synonym, realName] of Object.entries(synonyms)) {
        if (lowerName === synonym.toLowerCase() || lowerName.includes(synonym.toLowerCase())) {
            targetRecipe = realName;
            console.log(`🔄 Синоним: "${recipeName}" → "${targetRecipe}"`);
            break;
        }
    }
    
    let found = false;
    let matchedRecipe = null;
    
    function normalizeName(name) {
        return name.toLowerCase().trim().replace(/[^\wа-яё]/gi, ' ').replace(/\s+/g, ' ').trim();
    }
    
    const searchNormalized = normalizeName(targetRecipe);
    
    // Функция поиска в объекте рецептов
    function findInRecipeObject(obj, type, showFunction) {
        if (!obj) return false;
        for (let key of Object.keys(obj)) {
            const normalizedKey = normalizeName(key);
            if (normalizedKey === searchNormalized || 
                key.toLowerCase().includes(targetRecipe.toLowerCase()) || 
                targetRecipe.toLowerCase().includes(key.toLowerCase())) {
                matchedRecipe = key;
                console.log(`✅ Найден ${type}: ${matchedRecipe}`);
                if (showFunction) showFunction(matchedRecipe);
                return true;
            }
        }
        return false;
    }
    
    // Поиск по всем категориям
    found = findInRecipeObject(fullRecipes, 'салат', showSaladDetail);
    if (!found) found = findInRecipeObject(soupsFullRecipes, 'суп', showSoupDetail);
    if (!found) found = findInRecipeObject(mainsFullRecipes, 'горячее блюдо', showMainDetail);
    if (!found) found = findInRecipeObject(dessertsFullRecipes, 'десерт', showDessertDetail);
    if (!found) found = findInRecipeObject(drinksFullRecipes, 'напиток', showDrinkDetail);
    if (!found) found = findInRecipeObject(bakeryFullRecipes, 'выпечка', showBakeryDetail);
    if (!found) found = findInRecipeObject(breakfastFullRecipes, 'завтрак', showBreakfastDetail);
    if (!found) found = findInRecipeObject(saucesFullRecipes, 'соус', showSauceDetail);
    
    // Поиск в странах
    if (!found && typeof countriesData !== 'undefined') {
        for (const [countryId, country] of Object.entries(countriesData)) {
            for (let recipe of country.recipes) {
                const normalizedKey = normalizeName(recipe.name);
                if (normalizedKey === searchNormalized || 
                    recipe.name.toLowerCase().includes(targetRecipe.toLowerCase()) || 
                    targetRecipe.toLowerCase().includes(recipe.name.toLowerCase())) {
                    matchedRecipe = recipe.name;
                    found = true;
                    console.log(`✅ Найден рецепт из страны ${country.name}: ${matchedRecipe}`);
                    if (typeof showCountryDetail === 'function') {
                        showCountryDetail(countryId);
                    }
                    break;
                }
            }
            if (found) break;
        }
    }
    
    if (!found) {
        console.log(`❌ Рецепт не найден: ${recipeName}`);
        showToastMessage(`❌ Рецепт "${recipeName}" не найден. Попробуйте: "Мясо по-французски" или поищите в каталоге.`);
        if (typeof showPage === 'function') showPage('home');
    }
}

function saveChatHistoryToLocal() {
    const chatContainer = document.getElementById('chatMessages');
    if (!chatContainer) return;
    const messages = [];
    chatContainer.querySelectorAll('div[style*="justify-content"]').forEach(msg => {
        const isUser = msg.style.justifyContent === 'flex-end';
        const text = msg.querySelector('div')?.innerText || '';
        if (text) messages.push({ isUser, text });
    });
    localStorage.setItem('ai_chat_history', JSON.stringify(messages));
}

