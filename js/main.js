// Сбор статистики
function getDashboardStats() {
    const users = getUsers();
    const userCount = Object.keys(users).length;
    
    let totalFavorites = 0;
    for (let username in users) {
        if (users[username].favorites) totalFavorites += users[username].favorites.length;
    }
    
    let totalComments = 0;
    for (let username in users) {
        if (users[username].comments) totalComments += users[username].comments.length;
    }
    
    let totalRatings = 0;
    for (let username in users) {
        if (users[username].ratings) totalRatings += Object.keys(users[username].ratings).length;
    }
    
    const recipePopularity = {};
    for (let username in users) {
        if (users[username].favorites) {
            users[username].favorites.forEach(recipe => {
                recipePopularity[recipe] = (recipePopularity[recipe] || 0) + 2;
            });
        }
    }
    
    const topRecipes = Object.entries(recipePopularity)
        .sort((a, b) => b[1] - a[1])
        .slice(0, 5)
        .map(([name, score]) => ({ name, score }));
    
    return { users: userCount, favorites: totalFavorites, comments: totalComments, ratings: totalRatings, topRecipes };
}

